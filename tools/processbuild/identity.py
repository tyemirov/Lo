"""Record the exact locally built Process launcher identity in Go source."""

from pathlib import Path
import hashlib
import subprocess
import sys


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    if len(sys.argv) != 4 or sys.argv[1] not in ("build", "verify"):
        raise ValueError("expected build or verify, launcher path, and identity source path")
    action = sys.argv[1]
    paths = [Path(argument).absolute() for argument in sys.argv[2:]]
    for path in paths:
        path.relative_to(root)
        if path.resolve() != path:
            raise ValueError("Process build path must remain canonical inside Lo")
    launcher, output = paths
    if action == "build":
        launcher.parent.mkdir(parents=True, exist_ok=True)
        native = root / "internal/processhost/native"
        subprocess.run(
            ["clang", "-std=c11", "-Wall", "-Wextra", "-Werror",
             "-Wno-error=deprecated-declarations", str(native / "launcher.c"),
             str(native / "normalization.c"), "-lsandbox", "-o", str(launcher)],
            cwd=root, stdin=subprocess.DEVNULL, check=True,
        )
    digest = hashlib.sha256(launcher.read_bytes()).hexdigest()
    content = '// Code generated by tools/processbuild/identity.py; DO NOT EDIT.\n\npackage processhost\n\nconst nativeHelperSHA256 = "' + digest + '"\n'
    if action == "verify":
        if not output.exists() or output.read_text() != content:
            raise ValueError("Process launcher identity mismatch")
        return
    if not output.exists() or output.read_text() != content:
        output.write_text(content)


if __name__ == "__main__":
    main()
