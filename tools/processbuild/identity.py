"""Record one locally built Process launcher identity for the native runtime."""

from pathlib import Path
import hashlib
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "nativeruntime"))
from process_sdk import build_objects, invoke


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    if len(sys.argv) != 4 or sys.argv[1] not in ("build", "verify"):
        raise ValueError("expected build or verify, launcher path, and Rust identity path")
    action = sys.argv[1]
    paths = [Path(argument).absolute() for argument in sys.argv[2:]]
    for path in paths:
        path.relative_to(root)
        if path.resolve() != path:
            raise ValueError("Process build path must remain canonical inside Lo")
    launcher, rust_output = paths
    if action == "build":
        launcher.parent.mkdir(parents=True, exist_ok=True)
        native = root / "runtime/native/host/process"
        work = root / "_scratch/build-state/process-launcher"
        objects, receipt = build_objects(root, work, ("execution_token",))
        invoke(root, work,
               [receipt["compiler"]["path"], "-target", "aarch64-apple-darwin",
                "-mmacosx-version-min=27.0", "-isysroot", receipt["sdk"]["path"],
                "-std=c11", "-Wall", "-Wextra", "-Werror", "-fno-modules",
                "-Wno-error=deprecated-declarations", "-iquote", str(root / "runtime/native/include"),
                str(native / "launcher.c"), str(native / "normalization.c"),
                *[str(path) for path in objects], "-lsandbox", "-o", str(launcher)])
    digest = hashlib.sha256(launcher.read_bytes()).hexdigest()
    outputs = {
        rust_output: '// Code generated by tools/processbuild/identity.py; DO NOT EDIT.\n\npub const SHA256: &str = "' + digest + '";\n',
    }
    for output, content in outputs.items():
        if action == "verify":
            if not output.exists() or output.read_text() != content:
                raise ValueError("Process launcher identity mismatch")
        elif not output.exists() or output.read_text() != content:
            output.write_text(content)


if __name__ == "__main__":
    main()
