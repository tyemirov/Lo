// Command generatecheckpointprint pins the evaluator's Unicode quote contract.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"unicode"
)

const pinnedUnicode = "17.0.0"

func main() {
	output := flag.String("output", "", "Lo-local Rust module to generate")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "checkpoint print table: unexpected positional arguments")
		os.Exit(1)
	}
	if err := generate(*output); err != nil {
		fmt.Fprintln(os.Stderr, "checkpoint print table:", err)
		os.Exit(1)
	}
}

func generate(output string) error {
	if unicode.Version != pinnedUnicode {
		return fmt.Errorf("requires Go Unicode %s, got %s", pinnedUnicode, unicode.Version)
	}
	if output == "" {
		return fmt.Errorf("missing --output")
	}
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	module, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil || !strings.HasPrefix(string(module), "module github.com/MarcoPoloResearchLab/Lo\n") {
		return fmt.Errorf("run from the Lo repository root")
	}
	absolute, err := filepath.Abs(output)
	if err != nil {
		return err
	}
	parent, err := filepath.EvalSymlinks(filepath.Dir(absolute))
	if err != nil {
		return err
	}
	relative, err := filepath.Rel(root, parent)
	if err != nil || relative == ".." || strings.HasPrefix(relative, ".."+string(filepath.Separator)) {
		return fmt.Errorf("output must remain inside Lo")
	}
	absolute = filepath.Join(parent, filepath.Base(absolute))
	if _, err := os.Lstat(absolute); err == nil {
		resolved, resolveErr := filepath.EvalSymlinks(absolute)
		if resolveErr != nil || resolved != absolute {
			return fmt.Errorf("output must be a direct Lo-local file")
		}
	}
	file, err := os.Create(absolute)
	if err != nil {
		return err
	}
	defer file.Close()
	fmt.Fprint(file, `// Code generated by tools/nativeruntime/generatecheckpointprint; DO NOT EDIT.
// Pin: Go Unicode 17.0.0 unicode.IsPrint. No Go dependency at runtime.

pub fn quote(name: &str) -> String {
    let mut out = String::from("\"");
    for c in name.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\u{7}' => out.push_str("\\a"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{b}' => out.push_str("\\v"),
            c if c < ' ' || c == '\u{7f}' => out.push_str(&format!("\\x{:02x}", c as u32)),
            c if !printable(c) && (c as u32) <= 0xffff => {
                out.push_str(&format!("\\u{:04x}", c as u32))
            }
            c if !printable(c) => out.push_str(&format!("\\U{:08x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
fn printable(c: char) -> bool {
    let scalar = c as u32;
    NON_PRINTABLE
        .binary_search_by(|&(start, end)| {
            if end < scalar {
                std::cmp::Ordering::Less
            } else if start > scalar {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_err()
}
#[rustfmt::skip]
const NON_PRINTABLE: &[(u32, u32)] = &[
`)
	start := rune(-1)
	for scalar := rune(0); scalar <= unicode.MaxRune+1; scalar++ {
		if scalar <= unicode.MaxRune && !unicode.IsPrint(scalar) {
			if start < 0 {
				start = scalar
			}
		} else if start >= 0 {
			fmt.Fprintf(file, "    (0x%04x, 0x%04x),\n", start, scalar-1)
			start = -1
		}
	}
	if _, err = fmt.Fprintln(file, "];"); err != nil {
		return err
	}
	return file.Close()
}
